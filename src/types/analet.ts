export interface Comment {
  id: string;
  text: string;
  timestamp: Date;
  author?: string; // For future multi-user support
}


export interface Analet {
  id: number;
  statement: string;           // Natural language statement
  shortName?: string;          // Short 8-10 word name for skimmable display
  cellQL?: string;            // CellQL representation of the analysis
  variables_used?: string[];  // Canonical variable names referenced by the CellQL
  semantic_hints_text?: string; // Short deduped definitions for variables used
  explanation?: string;       // Description of what the grammar does
  tags?: string[];            // Tags for categorization and filtering
  embeddingInput?: string;    // Text used as input to generate the embedding

  // Unified analet type system
  type?: 'framing' | 'waypoint';  // Core classification: framing (UMAP training only) vs waypoint (displayed)
  source?: 'pipeline' | 'statement' | 'notebook' | 'random' | 'embedding' | 'waypoint' | 'perturbed' | 'framing' | 'explorer' | 'conceptual_statement' | 'generated' | 'derivation' | 'focus' | 'unknown'; // Source tracking for generation method
  status?: 'active' | 'deleted';  // Soft delete status - deleted items are filtered from UI
  embedding?: number[];       // For UMAP visualization
  location?: {
    id: string;
    x: number;
    y: number;
  };
  notebook?: {
    id?: string;
    cells: string[];
  };
  notebookFileName?: string;  // Optional filename for associated notebook
  notebookCellMetadata?: any; // Metadata for notebook cell association
  comments?: Comment[];      // User comments and notes

  // AI-generated content tracking
  isExplanationAIGenerated?: boolean;  // Whether explanation was generated by AI
  isExplanationAccepted?: boolean;     // Whether AI explanation has been accepted by user
  explanationGeneratedAt?: string;     // Timestamp of AI generation
  explanationAcceptedAt?: string;      // Timestamp of user acceptance

  // Constraint support for UMAP positioning
  isFixed?: boolean;           // Whether this analet's position is fixed
  fixedPosition?: {x: number, y: number}; // Constraint coordinates in UMAP space
  constraintStrength?: number; // How strongly to enforce the constraint (0-1)

  // Relationship tracking
  parentAnaletId?: number;    // ID of parent analet for derived analets
}

export interface AnalysisNote {
  id: number;
  content: string;           // Rich text content with @variable syntax
  type: 'note';              // Consistent with analet/bearing pattern
  status: 'active' | 'deleted'; // Soft delete status
  createdAt: string;
  updatedAt: string;
  tags?: string[];           // Optional categorization
  parentId?: string;         // For hierarchy positioning
  position?: { x: number; y: number }; // Coordinates for standalone map notes
  // Anchoring for list view (interstitial gaps between analets)
  anchor?: {
    beforeAnaletId?: number | 'START';
    afterAnaletId?: number | 'END';
  };
}


