  public async loadSemanticLayer(): Promise<SemanticLayerData | null> {
    try {
      // Try to load a complete semantic layer first
      const semanticLayer = this.context.workspaceState.get<SemanticLayerData>(WORKSPACE_KEYS.SEMANTIC_LAYER);

      if (semanticLayer) {
        return semanticLayer;
      }

      // If no complete semantic layer, build one from individual components
      const conceptualStatementsData = this.context.workspaceState.get<{ statements: ConceptualStatement[]; savedAt: string }>(WORKSPACE_KEYS.CONCEPTUAL_STATEMENTS);
      const variableModificationsData = this.context.workspaceState.get<{ modifications: { [variableName: string]: VariableModification }; savedAt: string }>(WORKSPACE_KEYS.VARIABLE_MODIFICATIONS);

      const conceptualStatements = conceptualStatementsData?.statements || [];
      const variableModifications = variableModificationsData?.modifications || {};
             // If we have any components, return a semantic layer
       if (conceptualStatements.length > 0 || Object.keys(variableModifications).length > 0) {
         const now = new Date().toISOString();
         const aggregatedSemanticLayer: SemanticLayerData = {
           id: `semantic-layer-${Date.now()}`,
           datasetName: 'current-dataset', // TODO: Get actual dataset name
           conceptualStatements,
           variableModifications,
           createdAt: variableModificationsData?.savedAt || conceptualStatementsData?.savedAt || now,
           lastModified: now,
           version: '1.0'
         };
        return aggregatedSemanticLayer;
      } else {
        return null;
      }
    } catch (error) {
      console.error('❌ [StateManagement] Failed to load semantic layer:', error);
      return null;
    }
  }

