  // === HIERARCHY STATE MANAGEMENT ===

  public async saveHierarchyState(hierarchyState: any): Promise<void> {
    try {
      // Convert Map to serializable object if needed
      const serializable = {
        ...hierarchyState,
        flatMap: hierarchyState.flatMap instanceof Map
          ? Object.fromEntries(hierarchyState.flatMap)
          : hierarchyState.flatMap,
        savedAt: new Date().toISOString()
      };

      await this.context.workspaceState.update(WORKSPACE_KEYS.HIERARCHY_STATE, serializable);
    } catch (error) {
      console.error('❌ [StateManagement] Failed to save hierarchy state:', error);
      throw error;
    }
  }

  public async loadHierarchyState(): Promise<any | null> {
    try {
      const hierarchyState = this.context.workspaceState.get(WORKSPACE_KEYS.HIERARCHY_STATE) as HierarchyStateData | undefined;

      if (!hierarchyState) {
        return null;
      }

      // Check the size of the hierarchy state to prevent loading corrupted massive states
      const stateSize = JSON.stringify(hierarchyState).length;
      const maxSizeBytes = 5 * 1024 * 1024; // 5MB limit

      if (stateSize > maxSizeBytes) {
        console.warn(`🚫 [StateManagement] Hierarchy state too large (${Math.round(stateSize / 1024)} KB), clearing corrupted state`);
        // Clear the corrupted state
        await this.context.workspaceState.update(WORKSPACE_KEYS.HIERARCHY_STATE, undefined);
        await this.context.workspaceState.update(WORKSPACE_KEYS.DETECTED_CLUSTERS, undefined);
        await this.context.workspaceState.update(WORKSPACE_KEYS.SELECTED_FOLDER, undefined);
        return null;
      }

      // Convert serialized object back to Map if needed
      const restored = {
        ...hierarchyState,
        flatMap: hierarchyState.flatMap instanceof Map
          ? hierarchyState.flatMap
          : new Map(Object.entries(hierarchyState.flatMap || {}))
      };
      return restored;
    } catch (error) {
      console.error('❌ [StateManagement] Failed to load hierarchy state:', error);
      return null;
    }
  }

