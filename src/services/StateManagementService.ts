  public async getStorageInfo(): Promise<{ [key: string]: any }> {
    const info: { [key: string]: any } = {};

    for (const [name, key] of Object.entries(WORKSPACE_KEYS)) {
      const data = this.context.workspaceState.get(this.applyStudyPrefix(key));
      info[name] = {
        key: this.applyStudyPrefix(key),
        exists: data !== undefined,
        size: data ? JSON.stringify(data).length : 0,
        type: Array.isArray(data) ? 'array' : typeof data
      };
    }

    return info;
  }

  private applyStudyPrefix(key: string): string {
    // Prefix keys with dataset in study mode
    try {
      const studyManager = StudyWorkspaceManager.getInstance(this.context);
      const prefix = studyManager.getWorkspaceKeyPrefix();
      return prefix ? `${prefix}${key}` : key;
    } catch {
      return key;
    }
  }

