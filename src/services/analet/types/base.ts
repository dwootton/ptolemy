/**
 * Base analet type definitions
 *
 * This module defines the core types for the analet generation pipeline:
 * - BaseAnalet: What adapters produce after calling OpenAI (DSL format)
 * - AdapterResponse: Response wrapper for adapter operations
 *
 * This replaces the old complex NormalizedAnaletInput → CoreGenerationService pipeline
 * with a simple BaseAnalet → AnaletEnrichmentService → Full Analet flow.
 */

import type { Analet } from '../../../types/analet';

/**
 * Base analet format returned by adapters after calling OpenAI
 * This is the "DSL response" format that contains the essential analet data
 * before enrichment with embeddings, locations, IDs, etc.
 */
export interface BaseAnalet {
  /** Human-readable analysis statement/question */
  statement: string;

  /** Short 8-10 word name for skimmable display */
  shortName: string;

  /** CellQL representation of the analysis */
  cellQL: string;

  /** Canonical variable names referenced by the CellQL (columns) */
  variables_used?: string[];

  /** Short, deduplicated semantic definitions for variables used */
  semantic_hints_text?: string;

  /** Brief explanation of what this analysis accomplishes */
  explanation: string;

  /** Categorization tags for grouping and filtering */
  tags: string[];
}

/**
 * Response from adapter after calling OpenAI directly
 * Wraps the base analets with success/error metadata
 */
export interface AdapterResponse {
  /** Whether the adapter operation succeeded */
  success: boolean;

  /** Array of base analets generated by the adapter */
  baseAnalets: BaseAnalet[];

  /** Error message if operation failed */
  error?: string;

  /** Optional metadata about the generation process */
  metadata?: {
    /** Unique identifier for this request */
    requestId: string;

    /** Source type that generated these analets */
    source: string;

    /** Time taken to process the request (ms) */
    processingTime: number;

    /** Additional context about the generation */
    context?: Record<string, any>;
  };
}

/**
 * Configuration for analet enrichment process
 * Used when converting BaseAnalet → Full Analet
 */
export interface EnrichmentConfig {
  /** Source type for the analets */
  source: NonNullable<Analet['source']>;

  /** Starting position for layout calculation */
  startPosition?: { x: number; y: number };

  /** Whether to generate embeddings */
  generateEmbeddings?: boolean;

  /** Additional metadata to include in final analets */
  additionalMetadata?: Record<string, any>;
}

/**
 * Result of the enrichment process
 */
export interface EnrichmentResult {
  /** Whether enrichment succeeded */
  success: boolean;

  /** Enriched analets (full Analet objects) */
  analets: any[]; // Will be typed as Analet[] when imported

  /** Error message if enrichment failed */
  error?: string;

  /** Metadata about the enrichment process */
  metadata?: {
    /** Number of analets processed */
    processedCount: number;

    /** Time taken for enrichment (ms) */
    enrichmentTime: number;

    /** Whether embeddings were generated */
    embeddingsGenerated: boolean;
  };
}
